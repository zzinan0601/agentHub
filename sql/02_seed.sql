--
-- username 은 반드시 소문자여야 한다. 앱이 로그인할 때 이름을 소문자로 바꿔
-- 대조하므로, 대문자로 넣어두면 같은 이름으로 들어와도 못 찾고 계정이 하나 더 생긴다.
-- (한글 이름은 대소문자가 없으므로 그대로 쓰면 된다)
-- ---------------------------------------------------------------------------

INSERT INTO users (username, display_name, is_admin, is_active)
VALUES ('홍길동', '홍길동', true, true)   -- <- 실제 관리자 이름으로 바꾼다
