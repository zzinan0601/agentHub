-- 관리자 계정
--
-- 앱은 "가장 먼저 로그인한 사람"을 자동으로 관리자로 만든다. 폐쇄망에 올린 뒤
-- 아무나 먼저 들어오면 그 사람이 관리자가 된다는 뜻이다. 의도한 사람이 관리자가
